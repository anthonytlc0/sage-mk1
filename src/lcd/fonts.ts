import { type Bitmap, parseBitmap } from './framebuffer';

/**
 * A bitmap font. Glyphs are proportional (each has its own width); `gap` blank columns separate neighbours and
 * `height` is the cell height every glyph shares. All three fonts are original pixel designs.
 */
export interface Font {
  readonly name: string;
  readonly height: number;
  readonly gap: number;
  readonly glyphs: ReadonlyMap<string, Bitmap>;
}

/**
 * Builds a font from drawings ('#' dark, '.' light, rows separated by whitespace). Throws if any glyph is not
 * exactly `height` rows tall, so a mis-typed glyph fails at load time rather than drawing a skewed character.
 */
function defineFont(name: string, height: number, gap: number, src: Readonly<Record<string, string>>): Font {
  const glyphs = new Map<string, Bitmap>();
  for (const [ch, drawing] of Object.entries(src)) {
    const g = parseBitmap(drawing);
    if (g.h !== height) throw new Error(`font ${name}: glyph ${JSON.stringify(ch)} is ${g.h} rows tall, expected ${height}`);
    glyphs.set(ch, g);
  }
  return { name, height, gap, glyphs };
}

/**
 * The glyph for `ch`; undefined if the font does not cover it. There is no fallback to the other case: a memory name
 * is drawn as it was typed, and FONT_SMALL and FONT_MEDIUM have lower case of their own.
 */
export function glyphOf(font: Font, ch: string): Bitmap | undefined {
  return font.glyphs.get(ch);
}

